// Host half of the CUDA runtime linked into GPU synthesizers.
//
// * the hash-set C ABI of `cpp/cpu/i64hashset.hpp`, backed by
//   `cuco::static_set`; handles are device pointers to an insert ref;
// * the `mgpu*` entry points that `gpu-to-llvm` emits for `gpu.launch_func`
//   and `gpu.binary` (the subset of MLIR's CudaRuntimeWrappers.cpp the
//   synthesizer uses), on the device's primary context so that they share
//   it with the CUDA runtime API used by cuco;
// * `_mlir_memref_to_llvm_alloc`/`free`, which `finalize-memref-to-llvm
//   {use-generic-functions}` calls for `memref.alloc`: every allocation is
//   managed memory, so the host-side `synthesize` loop and the kernels share
//   the arena, the solution, and the flags.

#include "i64hashset.cuh"

#include <cuda.h>
#include <cuda_runtime.h>

#include <cstdio>
#include <cstdlib>
#include <string>
#include <vector>

// Relocatable fatbin of `i64hashset_device.cu`, generated by build.rs.
extern "C" const unsigned char loom2_hashset_device_fatbin[];
extern "C" const std::size_t loom2_hashset_device_fatbin_size;

namespace {

[[noreturn]] void fail(const char *what, const char *detail) {
  std::fprintf(stderr, "loom2 cuda runtime: %s: %s\n", what, detail);
  std::exit(1);
}

void check(CUresult result, const char *what) {
  if (result == CUDA_SUCCESS)
    return;
  const char *name = "unknown error";
  cuGetErrorName(result, &name);
  fail(what, name);
}

void check(cudaError_t result, const char *what) {
  if (result != cudaSuccess)
    fail(what, cudaGetErrorString(result));
}

/// Make the primary context of device 0 current on this thread.
void use_primary_context() {
  static CUcontext context = [] {
    check(cuInit(0), "cuInit");
    CUdevice device;
    check(cuDeviceGet(&device, 0), "cuDeviceGet");
    CUcontext primary;
    check(cuDevicePrimaryCtxRetain(&primary, device), "cuDevicePrimaryCtxRetain");
    return primary;
  }();
  check(cuCtxSetCurrent(context), "cuCtxSetCurrent");
}

__global__ void insert_one_kernel(std::uint64_t set, std::int64_t key, bool *fresh) {
  *fresh = mlir_loom::gpu::insert(set, key);
}

} // namespace

extern "C" {

// ---------------------------------------------------------------- hash set

std::uint64_t mlir_loom_hashset_i64_create_handle(std::uint64_t capacity) {
  use_primary_context();
  // The owning set is never destroyed, exactly like the CPU tables.
  auto *set = new mlir_loom::gpu::Set{static_cast<std::size_t>(capacity),
                                       cuco::empty_key{mlir_loom::gpu::empty_key}};
  auto ref = set->ref(cuco::insert);
  mlir_loom::gpu::InsertRef *device = nullptr;
  check(cudaMalloc(&device, sizeof(ref)), "cudaMalloc(hash set ref)");
  check(cudaMemcpy(device, &ref, sizeof(ref), cudaMemcpyHostToDevice), "cudaMemcpy(hash set ref)");
  return static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(device));
}

/// Host-side insert for production filters that the inliner folded to
/// straight-line host code (nullary constructors).
bool mlir_loom_hashset_i64_insert_one(std::uint64_t set, std::int64_t key) {
  use_primary_context();
  static bool *fresh = [] {
    bool *flag = nullptr;
    check(cudaMalloc(&flag, sizeof(bool)), "cudaMalloc(insert flag)");
    return flag;
  }();
  insert_one_kernel<<<1, 1>>>(set, key, fresh);
  check(cudaGetLastError(), "insert_one_kernel");
  bool result = false;
  check(cudaMemcpy(&result, fresh, sizeof(bool), cudaMemcpyDeviceToHost), "cudaMemcpy(insert flag)");
  return result;
}

// ------------------------------------------------------------ allocation

void *_mlir_memref_to_llvm_alloc(std::size_t size) {
  use_primary_context();
  void *pointer = nullptr;
  check(cudaMallocManaged(&pointer, size == 0 ? 1 : size), "cudaMallocManaged");
  return pointer;
}

void *_mlir_memref_to_llvm_aligned_alloc(std::size_t alignment, std::size_t size) {
  // Managed allocations are aligned to at least 256 bytes.
  if (alignment > 256)
    fail("_mlir_memref_to_llvm_aligned_alloc", "alignment above 256 bytes");
  return _mlir_memref_to_llvm_alloc(size);
}

void _mlir_memref_to_llvm_free(void *pointer) { cudaFree(pointer); }

// ------------------------------------------------- mgpu (gpu-to-llvm ABI)

void *mgpuModuleLoad(void *data, std::size_t /*size*/) {
  use_primary_context();
  CUmodule module = nullptr;
  check(cuModuleLoadData(&module, data), "cuModuleLoadData");
  return module;
}

/// Load one `gpu.binary` in PTX form, linking it with the hash-set device
/// library so its `.extern` calls resolve.
void *mgpuModuleLoadJIT(void *data, int optimization_level, std::size_t size) {
  use_primary_context();
  std::string ptx(static_cast<const char *>(data), size);
  while (!ptx.empty() && ptx.back() == '\0')
    ptx.pop_back();

  std::vector<char> log(1 << 14, '\0');
  CUjit_option options[] = {CU_JIT_OPTIMIZATION_LEVEL, CU_JIT_ERROR_LOG_BUFFER,
                            CU_JIT_ERROR_LOG_BUFFER_SIZE_BYTES};
  void *values[] = {reinterpret_cast<void *>(static_cast<std::uintptr_t>(optimization_level)),
                    log.data(), reinterpret_cast<void *>(log.size())};
  CUlinkState link = nullptr;
  check(cuLinkCreate(3, options, values, &link), "cuLinkCreate");
  auto report = [&](CUresult result, const char *what) {
    if (result != CUDA_SUCCESS) {
      std::fprintf(stderr, "%s\n", log.data());
      check(result, what);
    }
  };
  report(cuLinkAddData(link, CU_JIT_INPUT_PTX, ptx.data(), ptx.size() + 1, "kernel.ptx", 0,
                       nullptr, nullptr),
         "cuLinkAddData(kernel)");
  report(cuLinkAddData(link, CU_JIT_INPUT_FATBINARY,
                       const_cast<unsigned char *>(loom2_hashset_device_fatbin),
                       loom2_hashset_device_fatbin_size, "i64hashset_device", 0, nullptr, nullptr),
         "cuLinkAddData(hash set)");
  void *cubin = nullptr;
  std::size_t cubin_size = 0;
  report(cuLinkComplete(link, &cubin, &cubin_size), "cuLinkComplete");
  CUmodule module = nullptr;
  check(cuModuleLoadData(&module, cubin), "cuModuleLoadData");
  check(cuLinkDestroy(link), "cuLinkDestroy");
  return module;
}

void mgpuModuleUnload(void *module) {
  // Called from global destructors, possibly after the CUDA runtime has torn
  // the context down; the process is exiting either way.
  cuModuleUnload(static_cast<CUmodule>(module));
}

void *mgpuModuleGetFunction(void *module, const char *name) {
  CUfunction function = nullptr;
  check(cuModuleGetFunction(&function, static_cast<CUmodule>(module), name), name);
  return function;
}

void mgpuLaunchKernel(void *function, std::intptr_t grid_x, std::intptr_t grid_y,
                      std::intptr_t grid_z, std::intptr_t block_x, std::intptr_t block_y,
                      std::intptr_t block_z, std::int32_t shared_memory, void *stream,
                      void **parameters, void **extra, std::size_t /*parameter_count*/) {
  use_primary_context();
  if (grid_x == 0 || grid_y == 0 || grid_z == 0)
    return;
  check(cuLaunchKernel(static_cast<CUfunction>(function), grid_x, grid_y, grid_z, block_x,
                       block_y, block_z, shared_memory, static_cast<CUstream>(stream),
                       parameters, extra),
        "cuLaunchKernel");
}

void *mgpuStreamCreate() {
  use_primary_context();
  CUstream stream = nullptr;
  check(cuStreamCreate(&stream, CU_STREAM_NON_BLOCKING), "cuStreamCreate");
  return stream;
}

void mgpuStreamDestroy(void *stream) {
  check(cuStreamDestroy(static_cast<CUstream>(stream)), "cuStreamDestroy");
}

void mgpuStreamSynchronize(void *stream) {
  check(cuStreamSynchronize(static_cast<CUstream>(stream)), "cuStreamSynchronize");
}

} // extern "C"
